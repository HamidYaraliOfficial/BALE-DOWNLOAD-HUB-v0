class Doc(BaseDocTemplate):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.toc: list[tuple[str, int]] = []

    def afterFlowable(self, fl):
        if isinstance(fl, H) and fl.level == 1:
            self.toc.append((fl.title, self.page))


def on_page(canv, doc):
    if doc.page == 1:
        return
    canv.saveState()
    canv.setFont("Vazir", 8.5)
    canv.setFillColor(MUTED)
    canv.drawRightString(A4[0] - 2 * cm, A4[1] - 1.3 * cm, shape("BALE DOWNLOAD HUB – راهنمای کاربر"))
    canv.drawCentredString(A4[0] / 2, 1.1 * cm, str(doc.page))
    canv.setStrokeColor(ACCENT)
    canv.setLineWidth(0.6)
    canv.line(2 * cm, A4[1] - 1.5 * cm, A4[0] - 2 * cm, A4[1] - 1.5 * cm)
    canv.restoreState()


